def find_txt(chapter_id):
    """查找章节TXT文件路径"""
    for root, dirs, files in os.walk(STORY_DIR):
        for fname in files:
            if not fname.endswith('.TXT'):
                continue
            if fname.startswith(f"{chapter_id:03d}：") or fname.startswith(f"{chapter_id}："):
                return os.path.join(root, fname)
    return None


def apply_cond3(chapter_id, new_cond3, dry_run=False):
    """将新条件3写入TXT文件"""
    txt_path = find_txt(chapter_id)
    if not txt_path:
        return False, "TXT not found"

    with open(txt_path, 'r', encoding='utf-8') as f:
        content = f.read()

    lines = content.split('\n')
    replaced = False
    old_val = ""

    # 从章节终止条件区域内找 "3.xxx" 行
    in_cond_section = False
    for i, line in enumerate(lines):
        stripped = line.strip()
        if '章节终止条件' in stripped:
            in_cond_section = True
            continue
        if in_cond_section and stripped.startswith('3.'):
            old_val = stripped[2:].strip()
            if not dry_run:
                lines[i] = f'3.{new_cond3}'
            replaced = True
            break
        if in_cond_section and stripped == '' and i > 0:
            # 空行可能结束条件区域，但继续找
            pass

    if not dry_run and replaced:
        with open(txt_path, 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines))

    return replaced, old_val


def main():
    import sys
    dry_run = '--dry-run' in sys.argv

    print("=" * 60)
    print("Phase 2: 条件3写回TXT" + (" (DRY RUN)" if dry_run else ""))
    print("=" * 60)

    total = len(COND3)
    success = 0
    fail = 0
    skipped = 0
    unchanged = 0

    for ch_id in sorted(COND3.keys()):
        if ch_id in SKIP:
            skipped += 1
            continue

        new_cond3 = COND3[ch_id]
        ok, old = apply_cond3(ch_id, new_cond3, dry_run=dry_run)

        if ok:
            if old == new_cond3:
                unchanged += 1
            else:
                success += 1
        else:
            print(f"  FAIL: Chapter {ch_id} — {old}")
            fail += 1

    print(f"\n  映射: {total} 章")
    print(f"  成功: {success} (条件3已更新)")
    print(f"  未变: {unchanged} (新旧一致)")
    print(f"  跳过: {skipped} (已手动改好)")
    print(f"  失败: {fail}")

    if dry_run:
        print("\n  DRY RUN — 未实际写入。用 python scripts/apply_cond3_direct.py 执行写入。")


if __name__ == '__main__':
    main()
