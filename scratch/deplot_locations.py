for fname, mapping in deplot_mapping.items():
    fpath = os.path.join(location_dir, fname)
    if not os.path.exists(fpath):
        print(f"WARN: file {fname} not found!")
        continue
    with open(fpath, "r", encoding="utf-8") as fp:
        content = fp.read()
    
    modified = False
    for old_txt, new_txt in mapping.items():
        if old_txt in content:
            content = content.replace(old_txt, new_txt)
            modified = True
        else:
            print(f"WARN in {fname}: target not found: {old_txt[:30]}...")
            
    if modified:
        with open(fpath, "w", encoding="utf-8") as fp:
            fp.write(content)
        print(f"Cleaned plot narratives in {fname}")

print("De-plotting script completed.")
